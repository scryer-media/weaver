use super::*;
use crate::pipeline::direct_store::sparse::{SparseMarking, mark_sparse_best_effort};

// An exclusively created provisional destination. Its logical output is charged
// once; repair overwrites do not allocate a second file. The run journal owns
// publication and repair epochs, and rejects old-epoch writes before reuse.
pub(crate) struct PositionalOutput {
    file: std::fs::File,
    budget: Arc<JobExtractionBudget>,
    len: u64,
}

impl PositionalOutput {
    pub(crate) fn write_at(&self, offset: u64, bytes: &[u8]) -> io::Result<usize> {
        self.budget.check_active_io()?;
        if offset
            .checked_add(bytes.len() as u64)
            .is_none_or(|end| end > self.len)
        {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "positional output exceeds member bounds",
            ));
        }
        #[cfg(unix)]
        let written = {
            use std::os::unix::fs::FileExt;
            self.file.write_at(bytes, offset)?
        };
        #[cfg(windows)]
        let written = {
            use std::os::windows::fs::FileExt;
            self.file.seek_write(bytes, offset)?
        };
        self.budget.check_active_io()?;
        Ok(written)
    }

    pub(crate) fn sync_data(&self) -> io::Result<()> {
        self.budget.check_active_io()?;
        self.file.sync_data()
    }

    pub(crate) fn set_times(&self, times: std::fs::FileTimes) -> io::Result<()> {
        self.file.set_times(times)
    }
}

impl Drop for PositionalOutput {
    fn drop(&mut self) {
        self.budget.writer_finished();
    }
}

impl ExtractionRoot {
    // The name is generated by its owning set. A collision refuses this mode
    // instead of replacing another set's partial. The capability-root parent
    // and entry guards from create_file apply before the exclusive open.
    pub(crate) fn create_positional_partial(
        &self,
        relative: &Path,
        len: u64,
        budget: &Arc<JobExtractionBudget>,
    ) -> Result<PositionalOutput, String> {
        self.create_positional_partial_with_marker(relative, len, budget, SparseMarking::Platform)
    }

    fn create_positional_partial_with_marker(
        &self,
        relative: &Path,
        len: u64,
        budget: &Arc<JobExtractionBudget>,
        marker: SparseMarking,
    ) -> Result<PositionalOutput, String> {
        let safe = self
            .validate_relative_path(&relative.to_string_lossy())
            .map_err(|error| budget.reject_unsafe_path(error))?;
        budget.check_member_metadata(&safe.to_string_lossy(), len)?;
        budget.note_entry(&safe)?;
        self.ensure_parents(&safe, budget)?;
        budget
            .reserve_write_bytes(0, len)
            .map_err(|error| error.to_string())?;
        let mut created = false;
        let result = (|| -> io::Result<std::fs::File> {
            let mut options = OpenOptions::new();
            options.read(true).write(true).create_new(true);
            let file = self.dir.open_with(&safe, &options)?;
            created = true;
            let file = file.into_std();
            mark_sparse_best_effort(&file, &marker);
            file.set_len(len)?;
            Ok(file)
        })();
        match result {
            Ok(file) => {
                budget.writer_started();
                Ok(PositionalOutput {
                    file,
                    budget: Arc::clone(budget),
                    len,
                })
            }
            Err(error) => {
                budget.rollback_write_reservation(len);
                if created {
                    let _ = self.dir.remove_file(&safe);
                }
                Err(format!(
                    "failed to create positional partial '{}': {error}",
                    safe.display()
                ))
            }
        }
    }

    // Internal workspace entries are not archive members. Keep their directory
    // out of entry quotas while retaining capability-relative, no-link guards.
    // Completion already excludes and reclaims this workspace after restart.
    pub(crate) fn positional_workspace(&self) -> Result<Self, String> {
        let name = Path::new(".weaver-chunks");
        match self.dir.create_dir(name) {
            Ok(()) => {}
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {}
            Err(error) => return Err(error.to_string()),
        }
        let dir = self
            .dir
            .open_dir_nofollow(name)
            .map_err(|error| error.to_string())?;
        Ok(Self {
            path: self.path.join(name),
            dir,
        })
    }

    // Publication is atomic with respect to destination-name collisions. Both
    // names use guarded capabilities; hard_link never replaces an existing
    // destination, including one created after the metadata pass. Filesystems
    // that cannot link the partial refuse this mode, leaving it owned and intact.
    pub(crate) fn publish_positional_partial(
        &self,
        source: &Self,
        partial: &Path,
        destination: &Path,
        budget: &Arc<JobExtractionBudget>,
    ) -> Result<(), String> {
        budget
            .check_active_io()
            .map_err(|error| error.to_string())?;
        let partial = source
            .validate_relative_path(&partial.to_string_lossy())
            .map_err(|error| budget.reject_unsafe_path(error))?;
        let destination = self
            .validate_relative_path(&destination.to_string_lossy())
            .map_err(|error| budget.reject_unsafe_path(error))?;
        self.ensure_parents(&destination, budget)?;
        let metadata = source
            .dir
            .symlink_metadata(&partial)
            .map_err(|error| error.to_string())?;
        if !metadata.is_file() || metadata.file_type().is_symlink() {
            return Err(budget
                .reject_unsafe_path("positional partial is not a regular file")
                .into());
        }
        source
            .dir
            .hard_link(&partial, &self.dir, &destination)
            .map_err(|error| error.to_string())?;
        // Keep the private alias until every member links successfully. A
        // later collision must leave the complete original available to retry.
        Ok(())
    }

    pub(crate) fn positional_alias_matches(
        &self,
        path: &Path,
        output: &PositionalOutput,
    ) -> io::Result<bool> {
        let actual = self.dir.symlink_metadata(path)?;
        if !actual.is_file() || actual.file_type().is_symlink() {
            return Ok(false);
        }
        let expected = cap_std::fs::Metadata::from_file(&output.file)?;
        #[cfg(unix)]
        {
            use cap_std::fs::MetadataExt;
            Ok(actual.dev() == expected.dev() && actual.ino() == expected.ino())
        }
        #[cfg(windows)]
        {
            use cap_primitives::fs::_WindowsByHandle;
            Ok(actual.volume_serial_number().is_some()
                && actual.file_index().is_some()
                && actual.volume_serial_number() == expected.volume_serial_number()
                && actual.file_index() == expected.file_index())
        }
    }

    pub(crate) fn remove_positional_partial(
        &self,
        path: &Path,
        output: &PositionalOutput,
    ) -> io::Result<()> {
        if !self.positional_alias_matches(path, output)? {
            return Err(io::Error::other(
                "positional alias no longer belongs to this output",
            ));
        }
        // As with runtime/fs.rs fingerprint cleanup, this assumes the staging
        // namespace has no concurrent external mutator between identity check
        // and unlink. Capability containment is retained; an observed replacement
        // is never removed. Other extraction sets only use no-replace publication.
        self.dir.remove_file(path)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root_and_budget() -> (tempfile::TempDir, ExtractionRoot, Arc<JobExtractionBudget>) {
        let temp = tempfile::tempdir().unwrap();
        let root = ExtractionRoot::open(temp.path()).unwrap();
        let limits = Arc::new(ExtractionLimits {
            max_job_bytes: 32,
            max_member_bytes: 24,
            max_entries: 8,
            max_ratio: 1,
            ratio_floor_bytes: 1 << 30,
            max_seconds: 60,
            min_free_bytes: 1,
            max_memory_bytes: 64 * MIB,
        });
        let budget = JobExtractionBudget::new(
            limits,
            temp.path().to_path_buf(),
            1,
            0,
            0,
            PipelineMetrics::new(),
        )
        .unwrap();
        (temp, root, budget)
    }

    #[test]
    fn positional_output_is_bounded_and_repair_is_charged_once() {
        let (temp, root, budget) = root_and_budget();
        let output = root
            .create_positional_partial(Path::new("owned.partial"), 16, &budget)
            .unwrap();
        assert_eq!(budget.total_written(), 16);
        assert_eq!(output.write_at(8, b"12345678").unwrap(), 8);
        assert_eq!(output.write_at(0, b"abcdefgh").unwrap(), 8);
        assert_eq!(output.write_at(8, b"ABCDEFGH").unwrap(), 8);
        assert!(output.write_at(15, b"xx").is_err());
        assert!(output.write_at(u64::MAX, b"x").is_err());
        assert_eq!(budget.total_written(), 16);
        output.sync_data().unwrap();
        output.set_times(std::fs::FileTimes::new()).unwrap();
        root.publish_positional_partial(
            &root,
            Path::new("owned.partial"),
            Path::new("member"),
            &budget,
        )
        .unwrap();
        assert_eq!(
            std::fs::read(temp.path().join("member")).unwrap(),
            b"abcdefghABCDEFGH"
        );
        budget.cancel();
        assert!(output.write_at(0, b"x").is_err());
    }

    #[test]
    fn positional_partial_remains_budgeted_and_writable_when_sparse_marking_fails() {
        let (temp, root, budget) = root_and_budget();
        let output = root
            .create_positional_partial_with_marker(
                Path::new("fallback.partial"),
                8,
                &budget,
                SparseMarking::AlwaysFail,
            )
            .unwrap();
        assert_eq!(budget.total_written(), 8);
        assert_eq!(output.write_at(4, b"tail").unwrap(), 4);
        assert_eq!(
            std::fs::read(temp.path().join("fallback.partial")).unwrap(),
            b"\0\0\0\0tail"
        );
        assert_eq!(output.write_at(0, b"head").unwrap(), 4);
        assert!(output.write_at(8, b"x").is_err());
        output.sync_data().unwrap();
        root.publish_positional_partial(
            &root,
            Path::new("fallback.partial"),
            Path::new("member"),
            &budget,
        )
        .unwrap();
        assert_eq!(
            std::fs::read(temp.path().join("member")).unwrap(),
            b"headtail"
        );
        assert_eq!(budget.total_written(), 8);
    }

    #[test]
    fn positional_partial_collisions_preserve_existing_files() {
        let (temp, root, budget) = root_and_budget();
        std::fs::write(temp.path().join("existing.partial"), b"keep").unwrap();
        assert!(
            root.create_positional_partial(Path::new("existing.partial"), 8, &budget)
                .is_err()
        );
        assert_eq!(
            std::fs::read(temp.path().join("existing.partial")).unwrap(),
            b"keep"
        );
        assert_eq!(budget.total_written(), 0);
        let _output = root
            .create_positional_partial(Path::new("owned.partial"), 8, &budget)
            .unwrap();
        std::fs::write(temp.path().join("member"), b"previous").unwrap();
        assert!(
            root.publish_positional_partial(
                &root,
                Path::new("owned.partial"),
                Path::new("member"),
                &budget
            )
            .is_err()
        );
        assert_eq!(
            std::fs::read(temp.path().join("member")).unwrap(),
            b"previous"
        );
        assert!(temp.path().join("owned.partial").exists());
        root.remove_positional_partial(Path::new("owned.partial"), &_output)
            .unwrap();
    }

    #[cfg(unix)]
    #[test]
    fn positional_workspace_and_destination_parents_refuse_links() {
        let (temp, root, _) = root_and_budget();
        let outside = tempfile::tempdir().unwrap();
        std::os::unix::fs::symlink(outside.path(), temp.path().join(".weaver-chunks")).unwrap();
        assert!(root.positional_workspace().is_err());
        assert!(std::fs::read_dir(outside.path()).unwrap().next().is_none());

        let (temp, root, budget) = root_and_budget();
        let workspace = root.positional_workspace().unwrap();
        let output = workspace
            .create_positional_partial(Path::new("owned.partial"), 8, &budget)
            .unwrap();
        output.write_at(0, b"verified").unwrap();
        std::os::unix::fs::symlink(outside.path(), temp.path().join("linked")).unwrap();
        assert!(
            root.publish_positional_partial(
                &workspace,
                Path::new("owned.partial"),
                Path::new("linked/member"),
                &budget
            )
            .is_err()
        );
        assert!(!outside.path().join("member").exists());
        assert_eq!(
            std::fs::read(temp.path().join(".weaver-chunks/owned.partial")).unwrap(),
            b"verified"
        );
    }

    #[test]
    fn rollback_preserves_a_replaced_alias_and_the_original_remains_retryable() {
        let (temp, root, budget) = root_and_budget();
        let workspace = root.positional_workspace().unwrap();
        let output = workspace
            .create_positional_partial(Path::new("owned.partial"), 8, &budget)
            .unwrap();
        output.write_at(0, b"verified").unwrap();
        root.publish_positional_partial(
            &workspace,
            Path::new("owned.partial"),
            Path::new("member"),
            &budget,
        )
        .unwrap();
        std::fs::remove_file(temp.path().join("member")).unwrap();
        std::fs::write(temp.path().join("member"), b"replacement").unwrap();
        assert!(
            root.remove_positional_partial(Path::new("member"), &output)
                .is_err()
        );
        assert_eq!(
            std::fs::read(temp.path().join("member")).unwrap(),
            b"replacement"
        );
        root.publish_positional_partial(
            &workspace,
            Path::new("owned.partial"),
            Path::new("retry"),
            &budget,
        )
        .unwrap();
        assert_eq!(
            std::fs::read(temp.path().join("retry")).unwrap(),
            b"verified"
        );
    }
}
