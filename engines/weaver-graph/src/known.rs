#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::{KNOWN_TYPES, known_type};

    #[test]
    fn known_types_are_sorted_lower_case_unique_and_bare() {
        let mut seen = BTreeSet::new();
        for group in KNOWN_TYPES {
            assert!(group.windows(2).all(|pair| pair[0] < pair[1]), "{group:?}");
            for extension in *group {
                assert_eq!(*extension, extension.to_ascii_lowercase());
                assert!(
                    !extension.is_empty() && !extension.contains('.'),
                    "{extension}"
                );
                assert!(seen.insert(*extension), "{extension} twice");
            }
        }
        assert!(seen.len() >= 700, "{}", seen.len());
    }

    #[test]
    fn known_types_name_no_archive_recovery_or_check_data() {
        let mut removed: Vec<String> = [
            "7z", "ace", "arc", "arj", "bin", "bz", "bz2", "cab", "chk", "crc", "disc", "ffmeta",
            "gz", "lz", "lzh", "lzma", "md5", "nzb", "par", "par2", "par3", "part", "rar", "rev",
            "sfv", "sha1", "sha256", "sha512", "srr", "srs", "tar", "tgz", "tmp", "xz", "z", "zip",
            "zst",
        ]
        .map(String::from)
        .to_vec();
        removed.extend((0..100).map(|volume| format!("r{volume:02}")));
        removed.extend((0..1000).map(|part| format!("{part:03}")));
        for extension in removed {
            assert!(!known_type(&format!("ember.{extension}")), "{extension}");
        }
    }

    #[test]
    fn a_known_type_is_read_off_the_last_dot_in_any_case() {
        for name in [
            "ember.mkv",
            "EMBER.MKV",
            "ember.srt",
            "ember.nfo",
            "ember.cbz",
            "ember.iso",
            "ember.flac",
            "ember.cr3",
            "ember.psd",
            "ember.vhd",
            "nested.dir/ember.Mkv",
        ] {
            assert!(known_type(name), "{name}");
        }
        for name in [
            "ember.bin",
            "ember.rar",
            "ember.r01",
            "ember.7z.001",
            "ember.par2",
            "ember.rev",
            "ember.7z",
            "ember.sfv",
            "ember",
            "d1c70000a4f2",
            "ember.mkv.dir/payload",
            "ember.",
        ] {
            assert!(!known_type(name), "{name}");
        }
    }
}
