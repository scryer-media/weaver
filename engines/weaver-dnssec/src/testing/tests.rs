fn rfc5155_appendix_a_hashes_are_independent_vectors() {
    // rfc5155.txt lines 1922..1934 (LF lines): every printed owner-name hash.
    // Salt/iterations are printed on line 1975 (NSEC3PARAM).
    for (owner, expected) in [
        ("example.", "0p9mhaveqvm6t7vbl5lop2u3t2rp3tom"),
        ("a.example.", "35mthgpgcu1qg68fab165klnsnk3dpvl"),
        ("ai.example.", "gjeqe526plbf1g8mklp59enfd789njgi"),
        ("ns1.example.", "2t7b4g4vsa5smi47k61mv5bv1a22bojr"),
        ("ns2.example.", "q04jkcevqvmu85r014c7dkba38o0ji5r"),
        ("w.example.", "k8udemvp1j2f7eg6jebps17vp3n8i58h"),
        ("*.w.example.", "r53bq7cc2uvmubfu5ocmm6pers9tk9en"),
        ("x.w.example.", "b4um86eghhds6nea196smvmlo4ors995"),
        ("y.w.example.", "ji6neoaepv8b5o6k4ev33abha8ht9fgc"),
        ("x.y.w.example.", "2vptu5timamqttgl4luu9kg21e0aor3s"),
        ("xx.example.", "t644ebqk9bibcna874givr6joj62mlhv"),
        (
            "2t7b4g4vsa5smi47k61mv5bv1a22bojr.example.",
            "kohar7mbb8dc2ce8a9qvl8hon4k53uhi",
        ),
    ] {
        let hash = nsec3_hash(&name(owner), &[0xaa, 0xbb, 0xcc, 0xdd], 12);
        assert_eq!(base32hex(&hash), expected);
        assert_eq!(
            crate::algorithm::nsec3_hash(&name(owner), &[0xaa, 0xbb, 0xcc, 0xdd], 12),
            hash
        );
    }
}

#[test]
fn resolver_joins_tree_and_keys_have_distinct_tags() {
    let root = Zone::new(Name::root(), KeyAlgorithm::P256).unwrap();
    let com = Zone::new(name("com."), KeyAlgorithm::Ed25519).unwrap();
    let mut leaf = Zone::new(name("example.com."), KeyAlgorithm::P256).unwrap();
    leaf.add_record(name("www.example.com."), RecordType::A, vec![192, 0, 2, 1]);
    // Start with an intentional collision: copied private key and metadata.
    leaf.keys[0] = root.keys[0].clone();
    let resolver = FakeResolver::new(vec![root, com, leaf]).unwrap();
    let tags = resolver
        .zones()
        .iter()
        .flat_map(|zone| zone.keys.iter().map(SigningKey::key_tag))
        .collect::<std::collections::BTreeSet<_>>();
    assert_eq!(tags.len(), 3);
    for (owner, rtype) in [
        ("www.example.com.", RecordType::A),
        (".", RecordType::DNSKEY),
        ("com.", RecordType::DS),
        ("com.", RecordType::DNSKEY),
        ("example.com.", RecordType::DS),
        ("example.com.", RecordType::DNSKEY),
    ] {
        let query = query(&name(owner), rtype);
        let parsed = Message::parse(&resolver.answer(&query).unwrap(), &query).unwrap();
        assert!(
            parsed
                .answer
                .iter()
                .any(|set| set.owner == query.name && set.rtype == rtype)
        );
    }
}

#[test]
fn resolver_emits_alias_wildcard_negative_and_tampered_messages() {
    let mut zone = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
    zone.add_record(name("target.example."), RecordType::A, vec![192, 0, 2, 1]);
    zone.add_record(
        name("alias.example."),
        RecordType::CNAME,
        name("target.example.").as_wire().to_vec(),
    );
    zone.add_record(
        name("redirect.example."),
        RecordType::DNAME,
        name("example.").as_wire().to_vec(),
    );
    zone.add_record(name("*.wild.example."), RecordType::A, vec![192, 0, 2, 2]);
    let mut resolver = FakeResolver::new(vec![zone]).unwrap();
    for (owner, expected) in [
        ("alias.example.", RecordType::CNAME),
        ("target.redirect.example.", RecordType::DNAME),
        ("a.wild.example.", RecordType::A),
    ] {
        let query = query(&name(owner), RecordType::A);
        let reply = resolver.reply(&query).unwrap();
        assert!(reply.answer.iter().any(|record| record.rtype == expected));
        assert!(Message::parse(&reply.encode(&query).unwrap(), &query).is_ok());
    }
    let query = query(&name("missing.example."), RecordType::A);
    assert_eq!(resolver.reply(&query).unwrap().rcode, 3);
    let nodata = query.clone();
    resolver.tamper(move |query, reply| {
        if query == &nodata {
            reply.rcode = 0;
            reply.strip_signatures();
            reply.additional.append(&mut reply.answer);
        }
    });
    let reply = Message::parse(&resolver.answer(&query).unwrap(), &query).unwrap();
    assert_eq!(reply.rcode, 0);
    assert!(reply.authority.iter().all(|set| set.rrsigs.is_empty()));
    resolver.set_reply(query.clone(), None);
    assert_eq!(resolver.answer(&query), None);
}

#[test]
fn collision_regeneration_updates_explicit_ds_and_retains_wrong_entries() {
    let mut root = Zone::new(Name::root(), KeyAlgorithm::P256).unwrap();
    let mut child = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
    child.keys[0] = root.keys[0].clone();
    child.add_record(name("www.example."), RecordType::A, vec![192, 0, 2, 1]);
    let mut ds = child.ds_records(2).unwrap();
    let mut wrong = ds[0].clone();
    wrong[4] ^= 1;
    ds.push(wrong.clone());
    root.delegate(child.apex.clone(), ds);
    let resolver = FakeResolver::new(vec![root, child]).unwrap();
    let rewritten = resolver.zones()[0]
        .delegations
        .get(&name("example."))
        .unwrap();
    assert!(rewritten.contains(&wrong));
    assert!(
        rewritten.contains(
            &resolver.zones()[1].keys[0]
                .ds_rdata(&name("example."), 2)
                .unwrap()
        )
    );
    let validator =
        crate::Validator::new(resolver.zones()[0].anchors().unwrap(), Policy::default()).unwrap();
    let question = crate::Question::new(name("www.example."), RecordType::A).unwrap();
    let (verdict, _) = drive(&validator, &resolver, question, 1_100_000);
    assert!(
        matches!(verdict, crate::Verdict::Secure { .. }),
        "{verdict:?}"
    );
}

#[test]
fn duplicate_zone_keys_preserve_retained_and_regenerated_ds_signers() {
    for signer in [0, 1] {
        let mut root = Zone::new(Name::root(), KeyAlgorithm::P256).unwrap();
        let mut child = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
        child.keys.push(child.keys[0].clone());
        child.dnskey_signers = vec![signer];
        child.record_signers = vec![signer];
        child.add_record(name("www.example."), RecordType::A, vec![192, 0, 2, 1]);
        // All supported digest types must follow the same key replacement.
        let entries = [1, 2, 4]
            .into_iter()
            .flat_map(|kind| child.ds_records(kind).unwrap())
            .collect();
        root.delegate(child.apex.clone(), entries);
        let resolver = FakeResolver::new(vec![root, child]).unwrap();
        let entries = resolver.zones()[0]
            .delegations
            .get(&name("example."))
            .unwrap();
        for kind in [1, 2, 4] {
            for key in &resolver.zones()[1].keys {
                assert!(entries.contains(&key.ds_rdata(&name("example."), kind).unwrap()));
            }
        }
        let validator =
            crate::Validator::new(resolver.zones()[0].anchors().unwrap(), Policy::default())
                .unwrap();
        let question = crate::Question::new(name("www.example."), RecordType::A).unwrap();
        let (verdict, _) = drive(&validator, &resolver, question, 1_100_000);
        assert!(
            matches!(verdict, crate::Verdict::Secure { .. }),
            "{verdict:?}"
        );
    }
}

#[test]
fn duplicate_ds_entries_are_expanded_once_per_original_digest() {
    let mut root = Zone::new(Name::root(), KeyAlgorithm::P256).unwrap();
    let mut child = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
    child.keys = vec![child.keys[0].clone(); 8];
    child.dnskey_signers = (0..8).collect();
    child.add_record(name("www.example."), RecordType::A, vec![192, 0, 2, 1]);
    let original = child.ds_records(2).unwrap();
    assert_eq!(original.len(), 8);
    assert!(original.iter().all(|entry| entry == &original[0]));
    root.delegate(child.apex.clone(), original);
    let resolver = FakeResolver::new(vec![root, child]).unwrap();
    let rewritten = &resolver.zones()[0].delegations[&name("example.")];
    assert_eq!(rewritten.len(), 8);
    assert_eq!(
        rewritten
            .iter()
            .collect::<std::collections::BTreeSet<_>>()
            .len(),
        8
    );
    let validator =
        crate::Validator::new(resolver.zones()[0].anchors().unwrap(), Policy::default()).unwrap();
    let question = crate::Question::new(name("www.example."), RecordType::A).unwrap();
    let (verdict, _) = drive(&validator, &resolver, question, 1_100_000);
    assert!(
        matches!(verdict, crate::Verdict::Secure { .. }),
        "{verdict:?}"
    );
}

#[test]
fn large_zones_return_small_sufficient_denial_proofs() {
    for denial in [
        DenialMode::Nsec,
        DenialMode::Nsec3 {
            salt: Vec::new(),
            iterations: 0,
            opt_out: false,
        },
    ] {
        let mut root = Zone::new(Name::root(), KeyAlgorithm::P256).unwrap();
        root.denial = denial;
        for index in 0..40 {
            root.add_record(
                name(&format!("x{index:02}.")),
                RecordType::A,
                vec![192, 0, 2, 1],
            );
        }
        root.add_record(name("*.wild."), RecordType::A, vec![192, 0, 2, 2]);
        let mut child = Zone::new(name("deep.branch."), KeyAlgorithm::P256).unwrap();
        child.add_record(name("www.deep.branch."), RecordType::A, vec![192, 0, 2, 3]);
        let resolver = FakeResolver::new(vec![root, child]).unwrap();
        for (owner, rtype, outcome) in [
            ("missing.", RecordType::A, crate::Outcome::NoSuchName),
            ("x00.", RecordType::AAAA, crate::Outcome::NoData),
            ("branch.", RecordType::AAAA, crate::Outcome::NoData),
            (
                "absent.wild.",
                RecordType::A,
                crate::Outcome::Records {
                    name: name("absent.wild."),
                    rdata: vec![vec![192, 0, 2, 2]],
                },
            ),
            ("absent.wild.", RecordType::AAAA, crate::Outcome::NoData),
            (
                "www.deep.branch.",
                RecordType::A,
                crate::Outcome::Records {
                    name: name("www.deep.branch."),
                    rdata: vec![vec![192, 0, 2, 3]],
                },
            ),
        ] {
            let validator =
                crate::Validator::new(resolver.zones()[0].anchors().unwrap(), Policy::default())
                    .unwrap();
            let question = crate::Question::new(name(owner), rtype).unwrap();
            let (verdict, queries) = drive(&validator, &resolver, question, 1_100_000);
            let crate::Verdict::Secure { answer } = verdict else {
                panic!("{owner}: {verdict:?}");
            };
            assert_eq!(answer.outcome, outcome);
            if owner == "www.deep.branch." {
                assert!(queries.contains(&query(&name("branch."), RecordType::DS)));
            }
            for query in queries {
                let reply = resolver.reply(&query).unwrap();
                let count = reply
                    .authority
                    .iter()
                    .filter(|r| matches!(r.rtype, RecordType::NSEC | RecordType::NSEC3))
                    .count();
                assert!(count <= 4, "{query:?}: {count} denial RRsets");
            }
        }
    }
}
