fn name(text: &str) -> Name {
    Name::from_text(text).unwrap()
}
fn query(owner: &Name, rtype: RecordType) -> Query {
    Query {
        name: owner.clone(),
        rtype,
    }
}
fn key(key: &SigningKey) -> Dnskey {
    let bytes = key.dnskey_rdata();
    match crate::rdata::parse(&bytes, 0, bytes.len(), 48)
        .unwrap()
        .kind
    {
        RdataKind::Dnskey(key) => key,
        _ => unreachable!(),
    }
}
fn ds(bytes: &[u8]) -> Ds {
    match crate::rdata::parse(bytes, 0, bytes.len(), 43).unwrap().kind {
        RdataKind::Ds(ds) => ds,
        _ => unreachable!(),
    }
}
fn dnskeys(zone: &Zone) -> Message {
    let query = query(&zone.apex, RecordType::DNSKEY);
    let reply = FakeReply {
        answer: zone.signed_rrset(&zone.apex, RecordType::DNSKEY).unwrap(),
        ..FakeReply::default()
    };
    Message::parse(&reply.encode(&query).unwrap(), &query).unwrap()
}

#[test]
fn generated_keys_sign_and_independent_validator_verifies() {
    for algorithm in [
        KeyAlgorithm::P256,
        KeyAlgorithm::Ed25519,
        KeyAlgorithm::Rsa2048,
        KeyAlgorithm::MlDsa44,
    ] {
        let mut zone = Zone::new(name("example."), algorithm).unwrap();
        // Synthetic data generated by this test, not a published signed vector.
        let owner = name("www.example.");
        zone.add_record(owner.clone(), RecordType::A, vec![192, 0, 2, 1]);
        zone.add_record(owner.clone(), RecordType::A, vec![192, 0, 2, 2]);
        let query = query(&owner, RecordType::A);
        let reply = FakeReply {
            answer: zone.signed_rrset(&owner, RecordType::A).unwrap(),
            ..FakeReply::default()
        };
        let parsed = Message::parse(&reply.encode(&query).unwrap(), &query).unwrap();
        let mut budget = WorkBudget::default();
        assert!(
            verify_rrset(
                &parsed.answer[0],
                &zone.apex,
                &[key(&zone.keys[0])],
                1_100_000,
                Policy::default(),
                &mut budget,
                SignatureLimit::CachedKeys(&mut 0)
            )
            .is_ok()
        );
        assert_eq!(budget.signatures, 1);
        if algorithm == KeyAlgorithm::Rsa2048 {
            assert_eq!(zone.keys[0].algorithm_number, 8);
            assert_eq!(zone.keys[0].public_key.len(), 260);
            assert_eq!(zone.keys[0].public_key.first(), Some(&3));
        }
        if algorithm == KeyAlgorithm::MlDsa44 {
            assert_eq!(zone.keys[0].algorithm_number, 18);
            assert_eq!(zone.keys[0].public_key.len(), 1312);
            let signature = reply
                .answer
                .iter()
                .find(|record| record.rtype == RecordType::RRSIG)
                .unwrap();
            assert_eq!(signature.rdata.len(), 18 + zone.apex.as_wire().len() + 2420);
        }
        let ds = ds(&zone.keys[0].ds_rdata(&zone.apex, 2).unwrap());
        assert!(matches!(
            prove_keys(
                &zone.apex,
                &[ds],
                300,
                &dnskeys(&zone),
                1_100_000,
                Policy::default(),
                &mut WorkBudget::default()
            ),
            Ok(KeyProof::Secure { .. })
        ));
    }
}

#[test]
fn signed_window_crossing_serial_wrap_verifies() {
    let mut zone = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
    zone.signature_window = SignatureWindow {
        inception: u32::MAX - 1000,
        expiration: 1000,
    };
    let parsed = dnskeys(&zone);
    let mut budget = WorkBudget::default();
    let verified = verify_rrset(
        &parsed.answer[0],
        &zone.apex,
        &[key(&zone.keys[0])],
        (1_u64 << 32) + 20,
        Policy::default(),
        &mut budget,
        SignatureLimit::CachedKeys(&mut 0),
    )
    .unwrap();
    assert_eq!(verified.ttl_bound, 300);
    assert_eq!(budget.signatures, 1);
}

#[test]
fn ds_match_must_itself_sign_dnskey_set() {
    let mut zone = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
    let signer = zone.add_key(KeyAlgorithm::Ed25519, 257).unwrap();
    zone.dnskey_signers = vec![signer];
    let ds = ds(&zone.keys[0].ds_rdata(&zone.apex, 2).unwrap());
    assert_eq!(
        prove_keys(
            &zone.apex,
            &[ds],
            300,
            &dnskeys(&zone),
            1_100_000,
            Policy::default(),
            &mut WorkBudget::default()
        ),
        Err(BogusReason::KeysNotProven)
    );
}

#[test]
fn stronger_ds_displaces_only_matching_sha1_digest() {
    let zone = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
    let weak = ds(&zone.keys[0].ds_rdata(&zone.apex, 1).unwrap());
    let mut strong = ds(&zone.keys[0].ds_rdata(&zone.apex, 2).unwrap());
    strong.digest[0] ^= 1;
    let policy = Policy {
        sha1_ds_digests: true,
        ..Policy::default()
    };
    assert_eq!(
        prove_keys(
            &zone.apex,
            &[weak, strong],
            300,
            &dnskeys(&zone),
            1_100_000,
            policy,
            &mut WorkBudget::default()
        ),
        // No DS digest matched a key; below an anchor the validator reports
        // this as KeysNotProven.
        Err(BogusReason::TrustAnchorMismatch)
    );
}

#[test]
fn rollover_accepts_signing_ds_in_either_order() {
    let mut zone = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
    let other = zone.add_key(KeyAlgorithm::Ed25519, 257).unwrap();
    let good = ds(&zone.keys[0].ds_rdata(&zone.apex, 2).unwrap());
    let bad = ds(&zone.keys[other].ds_rdata(&zone.apex, 2).unwrap());
    for entries in [vec![good.clone(), bad.clone()], vec![bad, good]] {
        assert!(matches!(
            prove_keys(
                &zone.apex,
                &entries,
                300,
                &dnskeys(&zone),
                1_100_000,
                Policy::default(),
                &mut WorkBudget::default()
            ),
            Ok(KeyProof::Secure { .. })
        ));
    }
}

#[test]
fn nsec_chain_is_canonical_and_closes_at_apex() {
    let mut zone = Zone::new(name("example."), KeyAlgorithm::P256).unwrap();
    for owner in ["z.example.", "a.example.", "b.a.example.", "c.example."] {
        zone.add_record(name(owner), RecordType::A, vec![192, 0, 2, 1]);
    }
    let chain = zone.denial_records().unwrap();
    let records: Vec<_> = chain
        .iter()
        .filter(|record| record.rtype == RecordType::NSEC)
        .collect();
    assert_eq!(records.len(), 5);
    assert_eq!(
        records
            .iter()
            .map(|record| record.owner.to_string())
            .collect::<Vec<_>>(),
        [
            "example.",
            "a.example.",
            "b.a.example.",
            "c.example.",
            "z.example."
        ]
    );
    for (record, next) in records.iter().zip(records.iter().cycle().skip(1)) {
        let parsed = crate::rdata::parse(&record.rdata, 0, record.rdata.len(), 47).unwrap();
        let RdataKind::Nsec(nsec) = parsed.kind else {
            unreachable!()
        };
        assert_eq!(nsec.next, next.owner);
    }
}

